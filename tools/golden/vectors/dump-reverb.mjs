#!/usr/bin/env node
// T04: reference vectors for the native reverb (native/core/src/fx/ir_gen.cpp, src/dsp/convolver.cpp), computed in
// the golden Chromium (tools/golden/vectors/lib.mjs launch(): the same build that rendered native/golden/out).
//
//   node tools/golden/vectors/dump-reverb.mjs [--out <dir>]   → <dir>/reverb-ir.txt, <dir>/reverb-conv.txt
//                                                              (default tools/golden/vectors/data)
//
// reverb-ir.txt: the engine's own IRs (fx.js FxGraph.reverb.getIR = irGen with createRng(hashSeed(seed|ir|key))),
// plus the irRecipe test's LCG IR. Per IR one line:
//   ir <engineSeed> <sr> <size> <damp> <key> <rngSeed> <len> <fnvL> <fnvR> <wordL> <wordR> <energy hex64>
//      idx=<i>:<hex32 L>,<hex32 R>;...                       (selected samples, exact float bits)
//   lcg <sr> <sizeSec> <damp> <len> <fnvL> <fnvR> <wordL> <wordR> <energy hex64>
//   fnv = FNV-1a 32 over the channel's float32 little-endian bytes; word = FNV-1a 32 over its uint32 words with the
//   prime 0x01000193 applied per word (two independent hashes: a bit-exact IR matches both).
// reverb-conv.txt: ConvolverNode renders (OfflineAudioContext). Per case:
//   case <name> <sr> <irLen> <irChannels> <inChannels> <normalize 0|1> <frames> <stride> <sumsqL hex64> <sumsqR hex64>
//   in/ir are regenerated by the reader from mulberry32 seeds (see genIr / genIn below, mirrored in test_reverb.cpp)
//   out <c> <hex32> <hex32> ...                             output channel c at frames 0, stride, 2*stride, ...
import fs from 'node:fs';
import path from 'node:path';
import { openPage, DATA, arg } from './lib.mjs';

const outDir = arg(process.argv, '--out', DATA);
fs.mkdirSync(outDir, { recursive: true });
const { browser, page, server, version } = await openPage();

const irCases = [];
for (const [size, damp] of [[0.5, 0.5], [0.18, 0.6], [0.42, 0.5], [0.65, 0.45], [0.9, 0.35], [1, 0.25]]) {
  irCases.push({ seed: 1, sr: 44100, size, damp });
}
for (const [size, damp] of [[0.25, 0.5], [0.8, 0.6], [0, 0], [0.3, 1], [0.55, 0.77]]) {
  irCases.push({ seed: 1, sr: 48000, size, damp });
}
irCases.push({ seed: 7, sr: 48000, size: 0.5, damp: 0.5 }, { seed: 7, sr: 44100, size: 0.25, damp: 0.5 });

const irLines = await page.evaluate(async (cases) => {
  const fx = await import('/js/engine/fx.js');
  const prng = await import('/js/shared/prng.js');
  const f32 = new Float32Array(1);
  const u32 = new Uint32Array(f32.buffer);
  const b64 = new Float64Array(1);
  const u64 = new BigUint64Array(b64.buffer);
  const hx32 = (v) => {
    f32[0] = v;
    return u32[0].toString(16).padStart(8, '0');
  };
  const hx64 = (v) => {
    b64[0] = v;
    return u64[0].toString(16).padStart(16, '0');
  };
  const fnvBytes = (a) => {
    const bytes = new Uint8Array(a.buffer, a.byteOffset, a.byteLength);
    let h = 0x811c9dc5;
    for (let i = 0; i < bytes.length; i++) h = Math.imul(h ^ bytes[i], 0x01000193);
    return (h >>> 0).toString(16).padStart(8, '0');
  };
  const fnvWords = (a) => {
    const w = new Uint32Array(a.buffer, a.byteOffset, a.length);
    let h = 0x811c9dc5;
    for (let i = 0; i < w.length; i++) h = Math.imul((h ^ w[i]) >>> 0, 0x01000193);
    return (h >>> 0).toString(16).padStart(8, '0');
  };
  const describe = (L, R) => {
    let e = 0;
    for (const ch of [L, R]) for (let i = 0; i < ch.length; i++) e += ch[i] * ch[i];
    const idx = [0, 1, 2, 100, 1000];
    for (let i = 0; i < L.length; i += 9973) idx.push(i);
    idx.push(L.length - 2, L.length - 1);
    const picks = [...new Set(idx)].filter((i) => i >= 0 && i < L.length).sort((a, b) => a - b)
      .map((i) => `${i}:${hx32(L[i])},${hx32(R[i])}`).join(';');
    return `${L.length} ${fnvBytes(L)} ${fnvBytes(R)} ${fnvWords(L)} ${fnvWords(R)} ${hx64(e)} idx=${picks}`;
  };
  const lines = [];
  for (const c of cases) {
    const ctx = new OfflineAudioContext({ numberOfChannels: 2, length: 128, sampleRate: c.sr });
    const g = new fx.FxGraph(ctx, { seed: c.seed, timer: new fx.AudioTimer(ctx) });
    const { key, ir } = g.reverb.getIR(c.size, c.damp);
    const rngSeed = prng.hashSeed(`${c.seed >>> 0}|ir|${key}`);
    lines.push(`ir ${c.seed} ${c.sr} ${c.size} ${c.damp} ${key} ${rngSeed} ` +
      describe(ir.getChannelData(0), ir.getChannelData(1)));
  }
  // test/phase1/engine/suites.mjs irRecipe: a Park-Miller LCG instead of mulberry32, bucket 2 s, damp .5
  for (const sr of [44100, 48000]) {
    const ctx = new OfflineAudioContext({ numberOfChannels: 2, length: 128, sampleRate: sr });
    const rng = { s: 1, next() { this.s = (this.s * 16807) % 2147483647; return this.s / 2147483647; } };
    const ir = fx.buildIR(ctx, rng, 2, 0.5);
    lines.push(`lcg ${sr} 2 0.5 ` + describe(ir.getChannelData(0), ir.getChannelData(1)).replace(/ idx=.*$/, ''));
  }
  return lines;
}, irCases);

// ---- ConvolverNode ------------------------------------------------------------------------------------------------
const convCases = [
  { name: 'direct-only', sr: 8000, irLen: 100, irCh: 2, inCh: 2, normalize: false, frames: 4000, stride: 2 },
  { name: 'two-stages', sr: 8000, irLen: 2500, irCh: 2, inCh: 2, normalize: false, frames: 9000, stride: 5 },
  { name: 'long', sr: 8000, irLen: 40000, irCh: 2, inCh: 2, normalize: false, frames: 52000, stride: 17 },
  { name: 'mono-in', sr: 8000, irLen: 20000, irCh: 2, inCh: 1, normalize: false, frames: 26000, stride: 13 },
  { name: 'normalized', sr: 8000, irLen: 2500, irCh: 2, inCh: 2, normalize: true, frames: 9000, stride: 5 },
  { name: 'normalized-48k', sr: 48000, irLen: 30000, irCh: 2, inCh: 2, normalize: true, frames: 36000, stride: 17 },
];
const convLines = await page.evaluate(async (cases) => {
  const mul = (seed) => {
    let a = seed >>> 0;
    return () => {
      a = (a + 0x6d2b79f5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  };
  // mirrored in native/core/tests/test_reverb.cpp (genIr / genIn): float32 arithmetic via Math.fround
  const genIr = (len, c) => {
    const r = mul(1000 + c);
    const a = new Float32Array(len);
    for (let i = 0; i < len; i++) a[i] = Math.fround((r() * 2 - 1) * 0.05 * Math.exp(-3 * i / len));
    return a;
  };
  const genIn = (frames, c) => {
    const r = mul(2000 + c);
    const a = new Float32Array(frames);
    const burst = Math.floor(frames / 4);
    for (let i = 0; i < burst; i++) a[i] = Math.fround((r() * 2 - 1) * 0.25);
    a[Math.floor(frames / 3)] = 0.5;
    a[Math.floor(frames / 3) + 777] = -0.3;
    return a;
  };
  const f32 = new Float32Array(1);
  const u32 = new Uint32Array(f32.buffer);
  const b64 = new Float64Array(1);
  const u64 = new BigUint64Array(b64.buffer);
  const hx32 = (v) => {
    f32[0] = v;
    return u32[0].toString(16).padStart(8, '0');
  };
  const hx64 = (v) => {
    b64[0] = v;
    return u64[0].toString(16).padStart(16, '0');
  };
  const lines = [];
  for (const c of cases) {
    const ctx = new OfflineAudioContext({ numberOfChannels: 2, length: c.frames, sampleRate: c.sr });
    const irb = new AudioBuffer({ numberOfChannels: c.irCh, length: c.irLen, sampleRate: c.sr });
    for (let ch = 0; ch < c.irCh; ch++) irb.copyToChannel(genIr(c.irLen, ch), ch);
    const conv = new ConvolverNode(ctx, { disableNormalization: !c.normalize });
    conv.buffer = irb;
    const inb = new AudioBuffer({ numberOfChannels: c.inCh, length: c.frames, sampleRate: c.sr });
    for (let ch = 0; ch < c.inCh; ch++) inb.copyToChannel(genIn(c.frames, ch), ch);
    const src = new AudioBufferSourceNode(ctx, { buffer: inb });
    src.connect(conv).connect(ctx.destination);
    src.start(0);
    const out = await ctx.startRendering();
    const sums = [0, 1].map((ch) => {
      let s = 0;
      for (const x of out.getChannelData(ch)) s += x * x;
      return hx64(s);
    });
    lines.push(`case ${c.name} ${c.sr} ${c.irLen} ${c.irCh} ${c.inCh} ${c.normalize ? 1 : 0} ${c.frames} ${c.stride} ` +
      sums.join(' '));
    for (let ch = 0; ch < 2; ch++) {
      const d = out.getChannelData(ch);
      const v = [];
      for (let i = 0; i < d.length; i += c.stride) v.push(hx32(d[i]));
      lines.push(`out ${ch} ${v.join(' ')}`);
    }
  }
  return lines;
}, convCases);

const head = (what) => `# ${what} from Chromium ${version} (tools/golden/vectors/dump-reverb.mjs)`;
fs.writeFileSync(path.join(outDir, 'reverb-ir.txt'), [head('Reverb IR vectors'), ...irLines, ''].join('\n'));
fs.writeFileSync(path.join(outDir, 'reverb-conv.txt'), [head('ConvolverNode vectors'), ...convLines, ''].join('\n'));
console.log(`wrote ${irLines.length} IR lines, ${convCases.length} convolver cases to ${outDir} (Chromium ${version})`);
await browser.close();
server.close();
