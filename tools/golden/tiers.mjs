#!/usr/bin/env node
// Regenerates the per-fixture tier table inside native/golden/README.md (between the tiers:begin / tiers:end markers)
// from manifest.json: the tolerance actually in force for every statistical fixture, why, and what makes it exact.
//   node tools/golden/tiers.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GOLD = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../native/golden');
const m = JSON.parse(fs.readFileSync(path.join(GOLD, 'manifest.json'), 'utf8'));
const st = m.fixtures.filter((e) => e.classification === 'statistical');
const t = m.tiers;
const L = [];
L.push(`${m.fixtures.length} fixtures: **${t.exact} exact**, **${t.statistical} statistical** ` +
  `(${t.exactIfPrngPorted} become ` +
  `exact once their PRNG streams are ported; ${t.statistical - t.exactIfPrngPorted} cannot, see "blockers").`, '',
  `Real statistical tolerances (not the 1.5 dB / 0.95 of ARCHITECTURE 8.2): bands **${t.statisticalBandsDb.min} to ` +
  `${t.statisticalBandsDb.max} dB** (widest: \`${t.widestBands.id}\`), envelope correlation ` +
    `**${t.statisticalEnvCorr.min} to ` +
  `${t.statisticalEnvCorr.max}** (lowest: \`${t.lowestEnvCorr.id}\`), RMS ${t.statisticalRmsDb.min} to ` +
    `${t.statisticalRmsDb.max} dB; ` +
  `envelope check OFF (corr -1, lag window +-200 ms) for ` +
    `${t.envelopeCheckOff.map((x) => `\`${x}\``).join(', ') || 'none'}.`, '',
  '| fixture | bands dB | env corr | lag ms | rms dB | exact if | blockers / note |', '|---|---|---|---|---|---|---|');
for (const e of st) {
  const x = e.tolerance;
  const streams = e.tier?.exactIf ? e.tier.exactIf.streams.join('+') : '-';
  const note = [...(e.tier?.blockers || []).map(() => 'not repeatable in Chromium'),
    e.tier?.weakWithoutPort ? 'weak without port' : ''].filter(Boolean).join('; ');
  L.push(`| ${e.id} | ${x.bandsDb} | ${x.envCorr} | ${x.envLagMs} | ${x.rmsDb} | ${streams} | ${note} |`);
}
const block = `<!-- tiers:begin (generated by tools/golden/tiers.mjs) -->\n${L.join('\n')}\n<!-- tiers:end -->`;
const rp = path.join(GOLD, 'README.md');
let r = fs.readFileSync(rp, 'utf8');
const re = /<!-- tiers:begin[\s\S]*?<!-- tiers:end -->/;
if (!re.test(r)) throw new Error('README.md has no tiers markers');
r = r.replace(re, block);
fs.writeFileSync(rp, r);
console.log(`README tier table: ${st.length} statistical rows`);
