#!/usr/bin/env node
// Generates src/params/params_gen.inc from native/contract/engine-api.json (params.rows).
//   node native/core/tools/gen-params.mjs            write the file
//   node native/core/tools/gen-params.mjs --check    exit 1 when the committed file is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const API = path.resolve(HERE, '../../contract/engine-api.json');
const OUT = path.resolve(HERE, '../src/params/params_gen.inc');

const api = JSON.parse(fs.readFileSync(API, 'utf8'));
const rows = api.params.rows;
const q = (s) => JSON.stringify(String(s));
const num = (v) => (v === undefined || v === null ? 'NAN' : Number.isInteger(v) ? `${v}.0` : String(v));
const wrap = (s) => s;
const smoothing = [...new Set(rows.map((r) => r.smoothing))];
const out = [];
out.push('// GENERATED by native/core/tools/gen-params.mjs from native/contract/engine-api.json. Do not edit.');
out.push(`// rows: ${rows.length}; contractVersion ${api.contractVersion}`);
out.push(`#define RIG_PARAM_COUNT ${rows.length}`);
out.push(`#define RIG_SMOOTHING_COUNT ${smoothing.length}`);
out.push('static const char *const kSmoothingText[RIG_SMOOTHING_COUNT] = {');
for (const s of smoothing) {
  const parts = s.match(/.{1,90}/g) || [''];
  out.push(`  ${parts.map(q).join('\n  ')},`);
}
out.push('};');
out.push('// path, kind (0 number, 1 bool, 2 enum), default, min, max, step, log, enum "a|b|c", coalesce, smoothing idx');
out.push('static const ParamRow kParamRows[RIG_PARAM_COUNT] = {');
for (const r of [...rows].sort((a, b) => (a.path < b.path ? -1 : 1))) {
  const kind = r.type === 'boolean' ? 1 : r.type === 'enum' ? 2 : 0;
  const def = kind === 1 ? (r.default ? '1.0' : '0.0') : kind === 2 ? `${Math.max(0, (r.enum || []).indexOf(r.default))}.0` : num(r.default);
  out.push(`  {${q(r.path)}, ${kind}, ${def}, ${num(r.min)}, ${num(r.max)}, ${num(r.step)}, ${r.curve === 'log' ? 'true' : 'false'},\n    ` +
    `${q((r.enum || []).join('|'))}, ${r.coalesce ? q(r.coalesce) : 'nullptr'}, ${smoothing.indexOf(r.smoothing)}},`);
}
out.push('};');
const text = out.join('\n') + '\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) {
    console.error('params_gen.inc is stale: run node native/core/tools/gen-params.mjs');
    process.exit(1);
  }
  console.log(`params_gen.inc up to date (${rows.length} rows)`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${OUT} (${rows.length} rows)`);
}
