#!/usr/bin/env node
// Builds native/contract/engine-api.json from engine-api.spec.mjs + app/js/shared/params.js + the instrument
// catalogue (app/js/engine/instruments.js loaded in node with a file-backed fetch).
//   node native/contract/tools/build-engine-api.mjs           write the JSON
//   node native/contract/tools/build-engine-api.mjs --check   exit 1 when the JSON is stale (params/catalogue drift)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CONTRACT = path.resolve(HERE, '..');
const REPO = path.resolve(CONTRACT, '..', '..');
const APP = path.join(REPO, 'app');
const OUT = path.join(CONTRACT, 'engine-api.json');
const NATIVE_SLOT_COUNT = 16;  // T00c / DECISIONS D3 (native/core RIG_MAX_SLOTS)

const imp = (rel) => import(pathToFileURL(path.join(REPO, rel)).href);

/** fetch() for the registry: http://app/<path> → app/<path> on disk; missing files answer 404. */
function fileFetch() {
  return async (u) => {
    const p = path.join(APP, new URL(String(u)).pathname.replace(/^\/+/, ''));
    const ok = fs.existsSync(p);
    const text = ok ? fs.readFileSync(p, 'utf8') : '';
    return { ok, status: ok ? 200 : 404, json: async () => JSON.parse(text), text: async () => text };
  };
}

async function catalogue() {
  const saved = globalThis.fetch;
  globalThis.fetch = fileFetch();
  try {
    const { InstrumentRegistry } = await imp('app/js/engine/instruments.js');
    const warns = [];
    const r = new InstrumentRegistry({
      manifestUrls: ['http://app/samples/manifest.json'],
      bufferCache: {},
      gainTrimsUrl: 'http://app/js/engine/gain-trims.json',
      warn: (m) => warns.push(m),
    });
    await r.init();
    const out = [];
    for (const e of r._all()) {
      const x = { ref: e.ref, name: e.name, group: e.group, hidden: !!e.hidden, params: e.params };
      if (e.widthDefault !== undefined) x.widthDefault = e.widthDefault;
      if (e.calibWindow) x.calibWindow = e.calibWindow;
      if (e.ref.type === 'sampler') {
        const d = r.samplers.get(e.ref.id);
        let lo = Infinity;
        let hi = -Infinity;
        let n = 0;
        for (const L of d.layers) for (const s of L.samples) {
          lo = Math.min(lo, s.midi);
          hi = Math.max(hi, s.midi);
          n++;
        }
        Object.assign(x, { range: [lo, hi], samples: n, layers: d.layers.length, decodeOpts: d.decodeOpts ?? null,
          gainTrimDb: d.gainTrim ?? d.gainTrimDb ?? null });
      } else {
        const t = r.gainTrims?.[e.ref.type]?.[e.ref.id];
        if (Number.isFinite(t)) x.gainTrimDb = t;
      }
      out.push(x);
    }
    return { instruments: out, droneTrimDb: r.gainTrims?.droneTrim ?? 0, warnings: warns };
  } finally {
    globalThis.fetch = saved;
  }
}

function paramRows(PARAMS, BEHAVIOUR, INSTRUMENT_PARAM_ENTRY) {
  const rules = BEHAVIOUR.map((b) => ({ ...b, re: new RegExp(b.match) }));
  const row = (e) => {
    const b = rules.find((x) => x.re.test(e.path));
    const r = { path: e.path, unit: e.unit, default: e.default };
    if (e.unit === 'enum') r.enum = e.enum;
    else {
      r.min = e.min;
      r.max = e.max;
    }
    for (const k of ['step', 'optional', 'words', 'dynamic', 'curve', 'label']) if (e[k] !== undefined) r[k] = e[k];
    const dyn = e.dynamic ? 'number|boolean|string' : 'number';
    r.type = e.unit === 'bool' ? 'boolean' : e.unit === 'enum' ? 'enum' : dyn;
    if (b) {
      r.coalesce = b.co === 'path' ? e.path : b.co;
      r.smoothing = b.smoothing;
      r.drives = b.drives;
      r.ref = b.ref;
    } else r.unmapped = true;
    return r;
  };
  const rows = PARAMS.map(row);
  const dyn = row({ ...INSTRUMENT_PARAM_ENTRY, min: null, max: null });
  return { rows, dynamic: dyn };
}

async function build() {
  const spec = await imp('native/contract/engine-api.spec.mjs');
  const params = await imp('app/js/shared/params.js');
  const touch = await imp('app/js/shared/touch-curve.js');
  const cat = await catalogue();
  const { rows, dynamic } = paramRows(params.PARAMS, spec.PARAM_BEHAVIOUR, params.INSTRUMENT_PARAM_ENTRY);
  const unmapped = rows.filter((r) => r.unmapped).map((r) => r.path);
  if (unmapped.length) throw new Error(`PARAM_BEHAVIOUR has no rule for: ${unmapped.join(', ')}`);
  return {
    $comment: 'GENERATED by native/contract/tools/build-engine-api.mjs from engine-api.spec.mjs, ' +
      'app/js/shared/params.js and the instrument registry. Do not edit by hand. Prose: ' +
          'native/docs/ENGINE_CONTRACT.md.',
    contractVersion: spec.CONTRACT_VERSION,
    protocol: spec.PROTOCOL,
    clock: spec.BRIDGE.timing,
    methods: spec.METHODS,
    notContract: spec.NOT_CONTRACT,
    events: spec.EVENTS,
    debugStats: spec.DEBUG_STATS,
    params: {
      grammar: {
        // T00c / DECISIONS D3: the native engine has 16 slots (slots.0 .. slots.15); the web engine keeps
        // params.SLOT_COUNT (4) and is the oracle for slots 0..3
        path: '^(slots\\.([0-9]|1[0-5])\\.(params\\.[A-Za-z_][A-Za-z0-9_]*|<row>)|fx\\.<unit>\\.<key>|' +
          'master\\.volume|drone\\.<key>)$',
        slotCount: NATIVE_SLOT_COUNT,
        webSlotCount: params.SLOT_COUNT,
        eqBandCount: params.EQ_BAND_COUNT,
        eqBandTypes: params.EQ_BAND_TYPES,
        clamp: 'bool: booleans, numbers >= .5, true/on/1; enum: member or rounded index; number: Number(v), ' +
            'NaN/null/"" → ' +
          'default, clamped, rounded when step 1; words pass; dynamic: booleans pass, numbers clamped to instrument ' +
              'meta',
        gainTaper: 'linear 0..2; UI fader position p → 2p^3',
      },
      count: rows.length,
      rows,
      dynamic,
      touch: { range: touch.TOUCH_RANGE, presets: touch.TOUCH_PRESETS, pedalCurves: touch.PEDAL_CURVES,
        formula: 'lo + span * clamp(vel/top,0,1)^shape; pedal log taper (10^(2x)-1)/99' },
      learnable: params.LEARNABLE,
      roleDefaults: params.ROLE_DEFAULTS,
    },
    instruments: { count: cat.instruments.filter((x) => !x.hidden).length, droneTrimDb: cat.droneTrimDb,
      list: cat.instruments },
    messages: { ...spec.BRIDGE, version: spec.PROTOCOL },
    quirks: spec.QUIRKS,
  };
}

const json = `${JSON.stringify(await build(), null, 2)}\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== json) {
    console.error('engine-api.json is stale: run node native/contract/tools/build-engine-api.mjs');
    process.exit(1);
  }
  console.log('engine-api.json is up to date');
} else {
  fs.writeFileSync(OUT, json);
  const j = JSON.parse(json);
  console.log(`wrote ${path.relative(REPO, OUT)}: ${j.methods.length} methods, ${j.events.length} events, ` +
    `${j.params.count} param rows, ${j.instruments.list.length} instruments, ${j.messages.ops.length} ops, ` +
    `${j.messages.events.length} native events, ${json.length} bytes`);
}
